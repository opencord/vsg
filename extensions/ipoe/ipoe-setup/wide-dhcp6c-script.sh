#!/bin/bash
#*************************************************************/
#** File:         wide-dhcp6c-script.sh                      */
#** Contents:     Contains shell script that would be        */
#**               automatically invoked by wide-dhcp6c-client*/
#**               after it receives IPv6 address, prefix     */
#**               info, etc. from dhcp6 server               */
#************************************************************/
time_begin=`date`
if [ -z "$TIME_ZONE" ]; then
   TIME_ZONE=EDT
   echo "Using $TIME_ZONE as local time zone"
fi
killall radvd-script.sh
#
#
# radvd configuration required dhcp6c to assign global IPv6
# address for LAN_INTF. However, dhcp6c, will not assign
# the IPV6 address to LAN_INTF until this script execution is
# completed. This is a chicken and egg question. To solve this
# problem, just kick off radvd_script and run it in the back
# ground mode to allow this script (wide-dhpc6c-script.sh)
# to complete its execution.
#
if [ -z $radvd_script ]; then
   radvd_script="/etc/wide-dhcpv6/radvd-script.sh"
fi
nohup $radvd_script 2>&1 &

#
# Generating the configuration file for dibbler-server
# 
if [ -n "$new_domain_name" -o -n "$new_domain_name_servers" -o -n "$new_ntp_servers" ]; then
  rm -f /etc/dibbler/server.conf
  touch  server.conf
cat > /etc/dibbler/server.conf << _EOF_ 
#********************************************/ 
#  server.conf file for dibbler-server      */ 
#  Generated by wide-dhcp6-client script    */  
#  Generation time: $time_begin  */           
#********************************************/   
  log-level 7 
  log-mode short
  stateless
  iface eth1 { 
      option dns-server  $new_domain_name_servers
      option domain  $new_domain_name
      option ntp-server  $new_ntp_servers
  }
_EOF_
fi
#
#
# Uncomment the following statements to restart radvd
# and dibbler-server
#
dibbler-server stop
dibbler-server start

